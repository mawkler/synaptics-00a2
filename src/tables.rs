#[cfg(test)]
mod tests {
    use sha2::{Digest, Sha256};

    #[test]
    fn program_is_python_validitys() {
        let hash: String = Sha256::digest(super::CAPTURE_PROGRAM)
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect();
        assert_eq!(
            hash,
            "1ca5f70d913faa0ef5a8db0289a169094348644fe633040931898359cb95c6d8"
        );
    }
}
