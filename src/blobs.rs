#[cfg(test)]
mod tests {
    use sha2::{Digest, Sha256};

    #[test]
    fn init_is_the_verified_blob() {
        let hash: String = Sha256::digest(super::INIT)
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect();
        assert_eq!(
            hash,
            "0f3128a1c93b49f0a5162bbad26b22ae02f539ab0668678ea090449922e39674"
        );
    }
}
